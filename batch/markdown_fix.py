"""배치 결과물(마크다운)의 모델 출력 흠집을 고치는 잎(leaf) 모듈.

백엔드(claude/gemini) 양쪽이 함께 쓰므로 어느 한쪽에 두지 않는다.
`agent` 도 다른 배치 모듈도 import 하지 않는다.
"""

import re


def fix_bullets(text):
    """`-항목` 처럼 불릿 뒤 공백이 빠진 줄을 `- 항목` 으로 고친다.

    `*`(강조일 수 있음)와 숫자(`-5도` = 음수)는 건드리지 않는다 — 진짜 불릿을 놓치는
    것은 미용상 흠이지만, 잘못 고치면 값의 의미가 바뀐다.
    """
    return re.sub(r"^-(?=[^\s\-\d])", "- ", text, flags=re.MULTILINE)
